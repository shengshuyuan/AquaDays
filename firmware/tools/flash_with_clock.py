#!/usr/bin/env python3
"""Flash AquaDays and bake the computer's Beijing time into the firmware.

Writes main/aq_flash_epoch.h, does an incremental build, then writes only the
app partition at 0x10000 (never bootloader / partition table / NVS erase).

Usage (from firmware/):
  python tools/flash_with_clock.py
  python tools/flash_with_clock.py -p /dev/cu.usbmodem1101
"""
from __future__ import annotations

import argparse
import glob
import os
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "main" / "aq_flash_epoch.h"
DEFAULT_PORTS = ["/dev/cu.usbmodem1101", "/dev/cu.usbmodem101", "/dev/ttyACM0"]


def beijing_local_epoch() -> int:
    # Same encoding as firmware Wi-Fi sync: UTC seconds + 8 hours.
    return int(time.time()) + 8 * 3600


def write_epoch_header(epoch: int) -> None:
    text = (
        "// Auto-generated by tools/flash_with_clock.py — do not edit by hand.\n"
        "// Beijing wall-clock seconds encoded the same way as Wi-Fi time (UTC + 8 hours).\n"
        "#pragma once\n"
        f"#define AQ_FLASH_EPOCH {epoch}LL\n"
    )
    HEADER.write_text(text, encoding="utf-8")
    wall = time.strftime("%Y-%m-%d %H:%M:%S", time.gmtime(epoch))
    print(f"flash clock: {wall} Beijing (epoch {epoch})")


def find_port(explicit: str | None) -> str:
    if explicit:
        return explicit
    env = os.environ.get("ESPPORT")
    if env:
        return env
    for pattern in DEFAULT_PORTS:
        matches = sorted(glob.glob(pattern)) if any(c in pattern for c in "*?") else (
            [pattern] if Path(pattern).exists() else []
        )
        if matches:
            return matches[0]
    # Last resort: any usbmodem / ACM device.
    for pattern in ("/dev/cu.usbmodem*", "/dev/ttyACM*"):
        matches = sorted(glob.glob(pattern))
        if matches:
            return matches[0]
    sys.exit("No serial port found. Plug in the device or pass -p /dev/cu.usbmodem…")


def run(cmd: list[str], **kw) -> None:
    print("+", " ".join(cmd))
    subprocess.check_call(cmd, cwd=ROOT, **kw)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("-p", "--port", help="serial port")
    ap.add_argument("--skip-build", action="store_true", help="use the bin already in build/")
    args = ap.parse_args()

    epoch = beijing_local_epoch()
    write_epoch_header(epoch)

    if not args.skip_build:
        # Touch main.c so the new header is definitely picked up.
        main_c = ROOT / "main" / "main.c"
        main_c.touch()
        run(["idf.py", "build"])

    bin_path = ROOT / "build" / "AquaDays.bin"
    if not bin_path.is_file():
        sys.exit(f"missing {bin_path}; build first")

    port = find_port(args.port)
    print(f"flashing app only on {port}")
    run([
        sys.executable, "-m", "esptool",
        "--chip", "esp32c3", "-p", port, "-b", "460800",
        "write_flash",
        "--flash_mode", "dio", "--flash_size", "8MB", "--flash_freq", "80m",
        "0x10000", str(bin_path),
    ])
    # Put the placeholder back so a later plain `idf.py build` does not bake in a stale clock.
    HEADER.write_text(
        "// Written by tools/flash_with_clock.py right before a flash. 0 means \"not injected\".\n"
        "// Beijing wall-clock seconds encoded the same way as Wi-Fi time (UTC + 8 hours).\n"
        "#pragma once\n"
        "#ifndef AQ_FLASH_EPOCH\n"
        "#define AQ_FLASH_EPOCH 0LL\n"
        "#endif\n",
        encoding="utf-8",
    )
    print("done — device should boot with the computer's Beijing time")


if __name__ == "__main__":
    main()
