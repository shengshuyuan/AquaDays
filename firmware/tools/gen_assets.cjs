#!/usr/bin/env node
// Generates main/aqua_assets_gen.h from prototype/assets/manifest.json.
// Run after re-exporting assets from the browser prototype: node firmware/tools/gen_assets.cjs
'use strict';
const fs = require('node:fs'), path = require('node:path');
const root = path.join(__dirname, '..', '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'prototype/assets/manifest.json'), 'utf8'));
const game = require(path.join(root, 'prototype/game.js'));
const species = game.catalog.map(k => k.id), sizes = [0.625, 1, 1.5], roles = ['swim', 'turn', 'walk'];
const frames = manifest.sprites.frames.map(f => {
  const kind = species.indexOf(f.species), size = sizes.indexOf(f.size), role = roles.indexOf(f.role);
  if (kind < 0 || size < 0 || role < 0) throw new Error(`Unknown frame ${JSON.stringify(f)}`);
  return `  {${kind}, ${size}, ${role}, ${f.frame}, ${f.width}, ${f.height}, ${f.offset}u},`;
});
const glyphs = [...manifest.font.glyphs].sort((a, b) => a.codepoint - b.codepoint)
  .map(g => `  {0x${g.codepoint.toString(16)}u, ${g.width}, ${g.offset}u},`);
const cfloat = v => `${Number.isInteger(v) ? v.toFixed(1) : v}f`;
const shade = n => { const s = manifest.sprites.runtime.shades[n]; return `{{${s.mul.map(cfloat).join(', ')}}, {${s.add.join(', ')}}}`; };
const out = `// Generated by firmware/tools/gen_assets.cjs from prototype/assets/manifest.json. Do not edit.
#pragma once
#include <stdint.h>

typedef struct { uint8_t kind, size, role, frame, w, h; uint32_t offset; } aq_frame_t;
typedef struct { uint32_t codepoint; uint8_t width; uint32_t offset; } aq_glyph_t;
typedef struct { float mul[3]; uint8_t add[3]; } aq_shade_t;

#define AQ_FRAME_COUNT ${frames.length}
#define AQ_GLYPH_COUNT ${glyphs.length}
#define AQ_GLYPH_H 12
#define AQ_SPRITE_BYTES ${manifest.sprites.frames.reduce((t, f) => t + f.length, 0)}u
#define AQ_PITCH_SHEAR ${cfloat(manifest.sprites.runtime.pitchShear.perPixel)}

static const aq_frame_t AQ_FRAMES[AQ_FRAME_COUNT] = {
${frames.join('\n')}
};
// Sorted by codepoint for binary search.
static const aq_glyph_t AQ_GLYPHS[AQ_GLYPH_COUNT] = {
${glyphs.join('\n')}
};
// Order: day, dayFar, night, nightFar.
static const aq_shade_t AQ_SHADES[4] = {
  ${['day', 'dayFar', 'night', 'nightFar'].map(shade).join(',\n  ')}
};
`;
fs.writeFileSync(path.join(__dirname, '..', 'main', 'aqua_assets_gen.h'), out);
console.log(`aqua_assets_gen.h: ${frames.length} frames, ${glyphs.length} glyphs`);
